// Writes AusFoodsTests.swift: real ingredient names from the test recipes and what jobs.js finds for each, so the Swift matcher can't drift from it.
const fs = require('fs');
const { resolve } = require('./jobs.js');
const rows = fs.readFileSync('results/answers.jsonl', 'utf8').trim().split('\n').map(l => JSON.parse(l)).filter(x => x.job === 'recipes' && x.answer);
const names = [...new Set(rows.flatMap(x => (x.answer.ingredients || []).map(i => i.name)))].filter(n => /^[\x20-\x7e]+$/.test(n)).sort();
const pick = names.filter((_, i) => i % 6 === 0);
const q = s => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const lines = pick.map(n => { const f = resolve(n); return `        (${q(n)}, ${f ? q(f.name.trim()) : 'nil'}),`; });
const swift = `import XCTest
@testable import CheatDays

/// Generated by tools/ai-test/make-swift-golden.js: the app's matcher finds what the test tool's matcher finds.
final class AusFoodsTests: XCTestCase {
    private let same: [(String, String?)] = [
${lines.join('\n')}
    ]

    func testTheFoodsAreBundled() {
        XCTAssertEqual(AusFoods.find("Olive oil")?.name, "Oil, olive")
        XCTAssertEqual(AusFoods.find("Olive oil")?.kcal, 883)
    }

    func testItFindsWhatTheTestToolFinds() {
        for (name, food) in same { XCTAssertEqual(AusFoods.find(name)?.name, food, name) }
    }

    func testAWrongNumberIsCorrectedAndARightOneLeftAlone() {
        func item(_ name: String, _ grams: Double, _ kcal: Double) -> JSON { ["name": name, "grams": grams, "kcal": kcal, "protein_g": 0, "carbs_g": kcal / 4, "fat_g": 0] }
        XCTAssertEqual(num(FoodReference.corrected(item("Dried spaghetti pasta", 100, 200)).item["kcal"]), 348)
        XCTAssertFalse(FoodReference.corrected(item("Olive oil", 10, 88)).changed, "already right")
        XCTAssertFalse(FoodReference.corrected(item("Olive oil", 10, 300)).changed, "too far off to trust the match")
        XCTAssertFalse(FoodReference.corrected(item("Zzzqqq", 100, 100)).changed, "nothing found")
    }

    func testAFinishedWeightFarFromItsIngredientsIsReplaced() {
        let tacos: [(name: String, grams: Double)] = [("Beef mince", 500), ("Taco shells", 160), ("Tomato", 300), ("Onion", 100)]
        let est = CookedWeight.estimate(tacos)
        XCTAssertEqual(CookedWeight.trusted(375, tacos), est, "a portion's weight given for the whole dish")
        XCTAssertEqual(CookedWeight.trusted(nil, tacos), est, "none given")
        XCTAssertEqual(CookedWeight.trusted(est, tacos), est)
    }

    func testASillyPortionIsNoticed() {
        func recipe(_ kcal: Double, serves: Double) -> JSON { ["portions": serves, "authentic": ["ingredients": [["kcal": kcal] as JSON]] as JSON] }
        XCTAssertFalse(FoodReference.portionLooksOff(recipe(2400, serves: 4)))
        XCTAssertTrue(FoodReference.portionLooksOff(recipe(100, serves: 4)))
        XCTAssertTrue(FoodReference.portionLooksOff(recipe(12000, serves: 2)))
    }
}
`;
fs.writeFileSync('../../native/CheatDaysTests/AusFoodsTests.swift', swift);
console.log(pick.length, 'names,', lines.filter(l => l.endsWith('nil),')).length, 'not found');
