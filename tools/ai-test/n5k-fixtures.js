// Writes native/CheatDaysTests/DatasetFixtures.swift from the saved Nutrition5k answers (n5k-run.js): each plate's
// weighed truth and the AI's estimate as it came back, for DatasetReplayTests to run through the app's checks offline.
//   node n5k-fixtures.js <dataset dir>
const fs = require('fs'), path = require('path');
const dir = process.argv[2];
const picked = JSON.parse(fs.readFileSync(path.join(dir, 'picked.json'), 'utf8'));
const answers = JSON.parse(fs.readFileSync(path.join(dir, 'answers.json'), 'utf8'));
const keep = ['name', 'usda_name', 'grams', 'kcal', 'protein_g', 'carbs_g', 'fat_g', 'numbers_from', 'size', 'tags', 'servings'];
const r1 = x => Math.round(x * 10) / 10;
const plates = picked.filter(d => answers[d.id]?.estimate?.parts?.length).map(d => {
  const e = answers[d.id].estimate;
  const parts = e.parts.map(p => Object.fromEntries(keep.filter(k => p[k] !== undefined).map(k => [k, p[k]])));
  const est = { name: e.name, portion_g: e.portion_g, unit: e.unit, notes: e.notes, size_unsure: e.size_unsure, parts };
  return { id: d.id, truth: { kcal: r1(d.kcal), grams: r1(d.grams), protein_g: r1(d.protein), carbs_g: r1(d.carbs), fat_g: r1(d.fat) }, estimate: est };
});
const json = JSON.stringify(plates);
if (json.includes('"""#')) throw new Error('fixture text would end the Swift string');
const out = `// Generated by tools/ai-test/n5k-fixtures.js; don't edit by hand.
// Nutrition5k (Thames et al., CVPR 2021, Google Research), CC BY 4.0: ${plates.length} weighed cafeteria plates from its
// test split, with the estimate Claude Sonnet gave for each one's overhead photo through the app's rules.
enum DatasetFixtures {
    static let json = #"""
${json}
"""#
}
`;
fs.writeFileSync(path.join(__dirname, '../../native/CheatDaysTests/DatasetFixtures.swift'), out);
console.log(`${plates.length} plates, ${(out.length / 1024).toFixed(0)} KB`);
